#include<iostream>
using namespace std;
int main(){
    int a,b;
    cout << "Enter the value of a : ";
    cin >> a;
    cout << "Enter the value of b : ";
    cin >> b;
    cout << "Sum = " << a+b << endl;
    cout << "Subtraction is = " << a-b << endl;
    cout << "Multiplication is = " << a*b << endl;
    cout << "Division is = " << a/b << endl;
    cout << "Remainder is = " << a%b << endl;
    return 0;
}